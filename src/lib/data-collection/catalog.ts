import { PREFER_NOT_TO_ANSWER } from "./fields";
import type { FieldCondition, FieldSource, FieldType, Vertical } from "./types";

/**
 * Field catalog per vertical. The deterministic setup engine picks from here;
 * an LLM-backed generator can return the same shape.
 */
export interface CatalogField {
  key: string;
  label: string;
  type: FieldType;
  prompt: string;
  options?: string[];
  /** Options are filled from the "options" setup answer (e.g. candidates). */
  optionsFromAnswer?: { extra: string[] };
  source?: FieldSource;
  condition?: FieldCondition;
  defaultCollect?: boolean;
  defaultRequired?: boolean;
  validationHint?: string;
}

export interface VerticalTemplate {
  vertical: Vertical;
  label: string;
  employeeNoun: string;
  objective: string;
  keywords: string[];
  audienceOptions: string[];
  optionsQuestion: string;
  optionsHelper: string;
  defaultOptions: string;
  afterOptions: string[];
  successOutcome: "Completed" | "Qualified" | "Callback";
  catalog: CatalogField[];
  knowledge: { title: string; description: string }[];
}

